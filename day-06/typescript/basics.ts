// Primitive types

let employeeName: string = "Rahul";
let age: number = 25;
let isActive: boolean = true;

// Array

let departments: string[] = [
    "IT",
    "HR",
    "Finance",
    "Marketing"
];

// Object

let employee: {
    id: number;
    name: string;
    salary: number;
} = {
    id: 1,
    name: "Rahul",
    salary: 50000
};

console.log("Name:", employeeName);
console.log("Age:", age);
console.log("Active:", isActive);
console.log("Departments:", departments);
console.log("Employee:", employee);